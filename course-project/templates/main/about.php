    <h2>Тема курсового проекта</h2>
    <p><strong>PolyStudy Hub</strong> — это студенческий сайт-справочник, посвящённый организации учебной нагрузки и сборке сильного backend-портфолио. Проект объединяет материалы, расчётный модуль и административную часть для управления контентом.</p>
    <p>Сайт построен на MVC-архитектуре на PHP и использует MySQL для хранения данных. Такая структура хорошо подходит под формат курсового проекта, потому что позволяет показать маршрутизацию, работу с шаблонами, контроллерами, моделями и SQL-запросами.</p>
